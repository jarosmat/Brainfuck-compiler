    [Fact]
    public void RecognizeSetMemoryZero()
    {
        StringReader stringReader = new StringReader("[-]");
        SecondLevelBytecodeGenerator bytecodeGenerator = new SecondLevelBytecodeGenerator(stringReader);
        byte[] correctResult = [0x02, 0x00, 0x00, 0x00, 0x08];
        byte[] actualResult = bytecodeGenerator.CreateByteCode();
        Assert.Equal(correctResult, actualResult);
    }

    [Fact]
    public void RecognizeMoveData()
    {
        StringReader stringReader = new StringReader("[->+<]");
        SecondLevelBytecodeGenerator bytecodeGenerator = new SecondLevelBytecodeGenerator(stringReader);
        byte[] correctResult = [0x02, 0x00, 0x00, 0x00, 0x09, 0x01, 0x01, 0x00, 0x00, 0x00];
        byte[] actualResult = bytecodeGenerator.CreateByteCode();
        Assert.Equal(correctResult, actualResult);
