using System.Data;
using BytecodeGenerator;
namespace UnitTests;

public class SecondLevelBytecodeGeneratorTests
{
    private static byte[] Generate(string input)
    {
        var streamReader = new StringReader(input);
        var byteCodeGenerator = new SecondLevelBytecodeGenerator(streamReader);
        var result = byteCodeGenerator.CreateByteCode();
        streamReader.Close();
        return result;
    }
    [Fact]
    public void SimpleGeneration()
    {
        const string input = "++-->><<,.";
        var result = Generate(input);
        Assert.Equal([0x02, 0x00, 0x00, 0x00, 0x00, 0x02, 0x01, 0x02, 0x03, 0x02, 0x00, 0x00, 0x00, 0x02, 0x02, 0x00, 0x00, 0x00, 0x05, 0x04], result);
    }
    [Fact]
    public void SimpleLoopGeneration()
    {
        const string input = "[+]++-->><<,.[->+<]";
        var result = Generate(input);
        Assert.Equal([0x02, 0x00, 0x00, 0x00, 0x08, 0x00, 0x02, 0x01, 0x02, 0x03, 0x02, 0x00, 0x00, 0x00, 0x02, 0x02, 0x00, 0x00, 0x00, 0x05, 0x04, 0x09, 0x01, 0x01, 0x00, 0x00, 0x00 ], result);
    }

    [Fact]
    public void WrongParenthesis1()
    {
        var stringReader = new StringReader("[[[[]]]");
        var byteCodeGenerator = new SecondLevelBytecodeGenerator(stringReader);
        Assert.Throws<SyntaxErrorException>(() => byteCodeGenerator.CreateByteCode());
    }
    
    [Fact]
    public void WrongParenthesis2()
    {
        var stringReader = new StringReader("[[]]]");
        var byteCodeGenerator = new SecondLevelBytecodeGenerator(stringReader);
        Assert.Throws<SyntaxErrorException>(() => byteCodeGenerator.CreateByteCode());
    }

    [Fact]
    public void RecognizeSetMemoryZero()
    {
        var stringReader = new StringReader("[-]");
        var bytecodeGenerator = new SecondLevelBytecodeGenerator(stringReader);
        byte[] correctResult = [0x02, 0x00, 0x00, 0x00, 0x08];
        var actualResult = bytecodeGenerator.CreateByteCode();
        Assert.Equal(correctResult, actualResult);
    }

