using System.Data;
using BytecodeGenerator;
namespace UnitTests;

public class SecondLevelBytecodeGeneratorTests
{
    [Fact]
    public void SimpleGeneration()
    {
        StringReader streamReader = new StringReader("++-->><<,.");
        SecondLevelBytecodeGenerator byteCodeGenerator = new SecondLevelBytecodeGenerator(streamReader);
        byte[] result = byteCodeGenerator.CreateByteCode();
        Assert.Equal([0x02, 0x00, 0x00, 0x00, 0x00, 0x02, 0x01, 0x02, 0x03, 0x02, 0x00, 0x00, 0x00, 0x02, 0x02, 0x00, 0x00, 0x00, 0x05, 0x04], result);
    }
    [Fact]
    public void SimpleLoopGeneration()
    {
        StringReader stringReader = new StringReader("[+]++-->><<,.[->+<]");
        SecondLevelBytecodeGenerator byteCodeGenerator = new SecondLevelBytecodeGenerator(stringReader);
        byte[] result = byteCodeGenerator.CreateByteCode();
        Assert.Equal([0x02, 0x00, 0x00, 0x00, 0x08, 0x00, 0x02, 0x01, 0x02, 0x03, 0x02, 0x00, 0x00, 0x00, 0x02, 0x02, 0x00, 0x00, 0x00, 0x05, 0x04, 0x09, 0x01, 0x01, 0x00, 0x00, 0x00 ], result);
    }

    [Fact]
    public void WrongParenthesis1()
    {
        StringReader stringReader = new StringReader("[[[[]]]");
        SecondLevelBytecodeGenerator byteCodeGenerator = new SecondLevelBytecodeGenerator(stringReader);
        Assert.Throws<SyntaxErrorException>(() => byteCodeGenerator.CreateByteCode());
    }
    
    [Fact]
    public void WrongParenthesis2()
    {
        StringReader stringReader = new StringReader("[[]]]");
        SecondLevelBytecodeGenerator byteCodeGenerator = new SecondLevelBytecodeGenerator(stringReader);
        Assert.Throws<SyntaxErrorException>(() => byteCodeGenerator.CreateByteCode());
