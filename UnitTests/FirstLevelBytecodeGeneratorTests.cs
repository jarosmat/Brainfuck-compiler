using System.Data;
using BytecodeGenerator;
using System.Text;
namespace UnitTests;

public class FirstLevelBytecodeGeneratorTests
{
    [Fact]
    public void SimpleGeneration()
    {
        StringReader streamReader = new StringReader("++-->><<,.");
        FirstLevelBytecodeGenerator byteCodeGenerator = new FirstLevelBytecodeGenerator(streamReader);
        byte[] result = byteCodeGenerator.CreateByteCode();
        Assert.Equal([0x00, 0x02, 0x01, 0x02, 0x03, 0x02, 0x00, 0x00, 0x00, 0x02, 0x02, 0x00, 0x00, 0x00, 0x05, 0x04], result);
    }
    [Fact]
    public void SimpleLoopGeneration()
    {
        StringReader stringReader = new StringReader("[+]++-->><<,.[->+<]");
        FirstLevelBytecodeGenerator byteCodeGenerator = new FirstLevelBytecodeGenerator(stringReader);
        byte[] result = byteCodeGenerator.CreateByteCode();
        Assert.Equal([0x06, 0x0C, 0x00, 0x00, 0x00, 0x00, 0x01, 0x07, 0x05, 0x00, 0x00, 0x00, 0x00, 0x02, 0x01, 0x02, 0x03, 0x02, 0x00, 0x00, 0x00, 0x02, 0x02, 0x00, 0x00, 0x00, 0x05, 0x04, 0x06, 0x34, 0x00, 0x00, 0x00, 0x01, 0x01, 0x03, 0x01, 0x00, 0x00, 0x00, 0x00, 0x01, 0x02, 0x01, 0x00, 0x00, 0x00, 0x07, 0x21, 0x00, 0x00, 0x00], result);
    }

    [Fact]
    public void WrongParenthesis1()
    {
        StringReader stringReader = new StringReader("[[[[]]]");
        FirstLevelBytecodeGenerator byteCodeGenerator = new FirstLevelBytecodeGenerator(stringReader);
        Assert.Throws<SyntaxErrorException>(() => byteCodeGenerator.CreateByteCode());
    }
    
    [Fact]
    public void WrongParenthesis2()
    {
        StringReader stringReader = new StringReader("[[]]]");
        FirstLevelBytecodeGenerator byteCodeGenerator = new FirstLevelBytecodeGenerator(stringReader);
        Assert.Throws<SyntaxErrorException>(() => byteCodeGenerator.CreateByteCode());
    }

    [Fact]
    public void NestedLoopGeneration()
    {
        StringReader stringReader = new StringReader("+++[-[>]+]--[+[>[]<][<]]");
        FirstLevelBytecodeGenerator byteCodeGenerator = new FirstLevelBytecodeGenerator(stringReader);
        byte[] correctResult = [0x00, 0x03, 0x06, 0x1F, 0x00, 0x00, 0x00, 0x01, 0x01, 0x06, 0x18, 0x00, 0x00, 0x00, 0x03, 0x01, 0x00, 0x00, 0x00, 0x07, 0x0E, 0x00, 0x00, 0x00, 0x00, 0x01, 0x07, 0x07, 0x00, 0x00, 0x00, 0x01, 0x02, 0x06, 0x5A, 0x00, 0x00, 0x00, 0x00, 0x01, 0x06, 0x46, 0x00, 0x00, 0x00, 0x03, 0x01, 0x00, 0x00, 0x00, 0x06, 0x3C, 0x00, 0x00, 0x00, 0x07, 0x37, 0x00, 0x00, 0x00, 0x02, 0x01, 0x00, 0x00, 0x00, 0x07, 0x2D, 0x00, 0x00, 0x00, 0x06, 0x55, 0x00, 0x00, 0x00, 0x02, 0x01, 0x00, 0x00, 0x00, 0x07, 0x4B, 0x00, 0x00, 0x00, 0x07, 0x26, 0x00, 0x00, 0x00];
        byte[] actualResult = byteCodeGenerator.CreateByteCode();
        Assert.Equal(correctResult, actualResult);
    }
}