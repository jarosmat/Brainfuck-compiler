using System.Text;
using BytecodeInterpreter;
namespace UnitTests;

[Collection("IO Collection")]
public class SimpleCodeRunnerTests
{
    private static string Run(byte[] code, string stringToPass)
    {
        using var consoleOut = new IoHandler(stringToPass);
        var firstLevelCodeRunner = new SimpleCodeRunner(code);
        var interpreter = new Interpreter();
        interpreter.Run(firstLevelCodeRunner);
        return consoleOut.GetOutput();        
    }
    private readonly UTF8Encoding _utf8 = new UTF8Encoding();
    private readonly Random _random = new Random();
    [Fact]
    public void SimpleAddition()
    {
        const string input = "";
        const string expectedOutput = "A";
        byte[] code = [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x04];
        var output = Run(code, input);
        Assert.Equal(expectedOutput, output);
    }
    [Fact]
    public void LoopAddition()
    {
        var randomByte  = _random.Next(48, 125);
        var charToPass = _utf8.GetChars([(byte)randomByte]);
        var stringToPass = new string(charToPass);
        byte[] code = [0x00, 0x00, 0x00, 0x00, 0x05, 0x06, 0x13, 0x00, 0x00, 0x00, 0x03, 0x00, 0x02, 0x01, 0x07, 0x05, 0x00, 0x00, 0x00, 0x03, 0x04];
        var output = Run(code, stringToPass);

        Assert.Equal(stringToPass, output);
    }
    
    
}